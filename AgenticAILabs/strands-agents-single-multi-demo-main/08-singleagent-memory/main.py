import asyncio
import os
from dotenv import load_dotenv

# Load environment variables
load_dotenv()

# Import the agent
from agents.agent import test_agent_v2_agent

async def main():
    """Main entry point for the agent"""
    print("🚀 Starting Test Agent v2...")
    
    try:
        # Initialize the agent
        agent = test_agent_v2_agent
        
        print("✅ Agent initialized successfully!")
        print("💬 You can now interact with the agent.")
        print("📝 Type 'exit' or 'quit' to stop the agent.")
        print("🔄 Streaming is enabled - responses will be streamed in real-time.")
        print()
        
        # Interactive loop
        while True:
            try:
                user_input = input("👤 You: ")
                
                if user_input.lower() in ['exit', 'quit', 'bye']:
                    print("👋 Goodbye!")
                    break
                
                if not user_input.strip():
                    continue
                
                print("🤖 Agent is thinking...")
                
                # Handle streaming response
                if True:
                    print("🔄 Streaming response:")
                    agent_stream = agent.stream_async(user_input)
                    async for event in agent_stream:
                        if hasattr(event, 'data'):
                            print(event.data, end='', flush=True)
                        elif hasattr(event, 'current_tool_use') and event.current_tool_use.get('name'):
                            print(f"\n🔧 USING TOOL: {event.current_tool_use['name']}")
                    print()  # New line after streaming
                else:
                    # Handle non-streaming response
                    response = await agent(user_input)
                    print(f"🤖 Test Agent v2: {response}")
                
                print()
                
            except KeyboardInterrupt:
                print("\n👋 Goodbye!")
                break
            except Exception as e:
                print(f"❌ Error: {e}")
                print("🔄 Please try again.")
                print()
                
    except Exception as e:
        print(f"❌ Failed to initialize agent: {e}")
        return 1
    
    return 0

if __name__ == "__main__":
    exit_code = asyncio.run(main())
    exit(exit_code)
